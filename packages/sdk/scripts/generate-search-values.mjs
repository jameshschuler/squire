import { writeFileSync } from "node:fs";

const [url, out] = process.argv.slice(2);
const response = await fetch(url);
const spec = await response.json();
const values = {};
for (const [path, item] of Object.entries(spec.paths)) {
  const resource = /^\/(\w+)\/search$/.exec(path)?.[1];
  for (const { name, schema } of (resource && item.get.parameters) || []) {
    if (name !== "detailed" && schema.enum) {
      const isBoolean = schema.enum.length === 2 && schema.enum.every((v) => v === "true" || v === "false");
      (values[resource] ??= {})[name] = isBoolean ? [true, false] : schema.enum;
    }
  }
}
writeFileSync(
  out,
  `// Generated by scripts/generate-search-values.mjs from the API spec. Do not edit.\n\nexport const SEARCH_VALUES = ${JSON.stringify(values, null, 2)} as const;\n`,
);
